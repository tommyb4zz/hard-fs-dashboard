/**
 * Initialize only the synthetic block array.
 *
 * Input: instance must be zero. Returns -1 for another instance, otherwise erases all 64
 * memory blocks to 0xFF and returns BSP_ERROR_NONE. Reinitialization discards host
 * contents; it does not discover a real card.
 */
int32_t BSP_MMC_Init(uint32_t instance) {
  if (instance != 0U)
    return -1;
  memset(storage, 0xFF, sizeof(storage));
  return BSP_ERROR_NONE;
}
/**
 * Report a deliberately small host capacity covering the logger's fixed starting block.
 *
 * Inputs: instance zero and writable info. Returns -1 for a wrong instance/null pointer;
 * on success writes total block count 4160 so production block 4096 has a 64-block region.
 * This deliberately small test capacity is not board capacity.
 */
int32_t BSP_MMC_GetCardInfo(uint32_t instance, BSP_MMC_CardInfo *info) {
  if (instance != 0U || info == NULL)
    return -1;
  info->LogBlockNbr = 4096U + 64U;
  return BSP_ERROR_NONE;
}
/**
 * Check an address range before fake storage access.
 *
 * Inputs: block/count are 512-byte logical block indices/count. Returns true only for a
 * positive range entirely in [4096,4160). Subtraction after the lower/upper guards avoids
 * overflow from block+count; storage remains unchanged.
 */
static bool storage_range(uint32_t block, uint32_t count) {
  return block >= 4096U && block < 4160U && count > 0U && count <= 4160U - block;
}
/**
 * Read bounded fake blocks.
 *
 * Inputs: instance zero, writable bytes and bounded block/count. Returns -1 on invalid
 * range/pointer/instance, otherwise copies count*512 bytes from storage and returns
 * BSP_ERROR_NONE. There is no asynchronous DMA, cache maintenance or card-busy state.
 */
int32_t BSP_MMC_ReadBlocks(uint32_t instance, uint32_t *bytes, uint32_t block, uint32_t count) {
  if (instance != 0U || bytes == NULL || !storage_range(block, count))
    return -1;
  memcpy(bytes, storage[block - 4096U], (size_t)count * 512U);
  return BSP_ERROR_NONE;
}
/**
 * Write bounded fake blocks.
 *
 * Inputs: instance zero, readable bytes and bounded block/count. Returns -1 on validation
 * failure, otherwise replaces count*512 storage bytes and returns BSP_ERROR_NONE. Data
 * persists only for this host process.
 */
int32_t BSP_MMC_WriteBlocks(uint32_t instance, uint32_t *bytes, uint32_t block, uint32_t count) {
  if (instance != 0U || bytes == NULL || !storage_range(block, count))
    return -1;
  memcpy(storage[block - 4096U], bytes, (size_t)count * 512U);
  return BSP_ERROR_NONE;
}
/**
 * Clear the bounded binary-export sink.
 *
 * Inputs: none. Returns nothing; sets wire_size to zero before a dump so exports do not
 * append to an earlier export. The underlying array is not erased because only the newly
 * counted prefix is saved.
 */
void dashboard_host_export_begin(void) {
  wire_size = 0;
}
/**
 * Capture binary export bytes, never a serial device.
 *
 * Inputs: bytes contains size bytes; uart and timeout are ignored. Returns HAL_ERROR when
 * the 65536-byte memory sink lacks room, otherwise appends bytes, advances wire_size and
 * returns HAL_OK. No serial device, wall-clock wait or partial write occurs.
 */
HAL_StatusTypeDef
HAL_UART_Transmit(UART_HandleTypeDef *uart, uint8_t *bytes, uint16_t size, uint32_t timeout) {
  (void)uart;
  (void)timeout;
  if (size > sizeof(wire) - wire_size)
    return HAL_ERROR;
  memcpy(wire + wire_size, bytes, size);
  wire_size += size;
  return HAL_OK;
}
/**
 * Write the captured binary stream to a caller-selected ordinary output file.
 *
 * Input: path names an ordinary output file. Returns false on open/short-write/close
 * failure; writes the counted wire prefix in binary and closes even when fwrite is short.
 * The memory sink is retained for inspection/reuse; no CAN/UART device is opened.
 */
bool dashboard_host_export_save(const char *path) {
  FILE *file = fopen(path, "wb");
  if (!file)
    return false;
  bool ok = fwrite(wire, 1, wire_size, file) == wire_size;
  return fclose(file) == 0 && ok;
}
