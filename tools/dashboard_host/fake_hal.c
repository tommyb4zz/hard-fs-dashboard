UART_HandleTypeDef hcom_uart[1];
static uint32_t host_tick;
typedef struct {
  FDCAN_RxHeaderTypeDef header;
  uint8_t data[64];
} host_rx_t;
static host_rx_t rx[DASHBOARD_HOST_RX_LIMIT];
static unsigned rx_read, rx_write;
static dashboard_host_tx_t outgoing;
static bool tx_pending;
static uint8_t storage[64][512];
static uint8_t wire[65536];
static size_t wire_size;

/**
 * Set the clock read by the unchanged production scheduler.
 *
 * Input: tick is an absolute unsigned millisecond value chosen by the command runner.
 * Returns nothing; replaces host_tick only. The fake imposes no monotonic rule; the T
 * command parser enforces it before calling.
 */
void dashboard_host_set_tick(uint32_t tick) {
  host_tick = tick;
}
/**
 * Read simulated time without waiting.
 *
 * Inputs: none. Returns host_tick in milliseconds with no mutation or sleep; production
 * request-period/timeout arithmetic reads this value.
 */
uint32_t HAL_GetTick(void) {
  return host_tick;
}
/**
 * Convert a canonical byte length to the vendor HAL's DLC encoding.
 *
 * Input: size is a payload byte count. Returns the index of the 16 canonical HAL DLC sizes
 * (0..8,12,16,20,24,32,48,64), or -1. No frame or queue state changes.
 */
static int host_dlc(size_t size) {
  static const uint8_t lengths[16] = {0, 1, 2, 3, 4, 5, 6, 7, 8, 12, 16, 20, 24, 32, 48, 64};
  for (unsigned i = 0; i < 16; i++)
    if (lengths[i] == size)
      return (int)i;
  return -1;
}
/**
 * Add one frame to the finite receive batch, retaining metadata for decoder rejection
 * tests.
 *
 * Inputs: id and metadata describe a synthetic frame; data contains size bytes and can be
 * null only for size zero. Returns false for unsupported lengths, full 128-entry batch or
 * absent payload; otherwise copies bytes/metadata into the next RX slot. Rejection by the
 * production protocol decoder happens later.
 */
bool dashboard_host_receive(
    uint32_t id, bool extended, bool remote, bool fd, const uint8_t *data, size_t size) {
  int dlc = host_dlc(size);
  if (dlc < 0 || rx_write >= DASHBOARD_HOST_RX_LIMIT || (size && data == NULL))
    return false;
  host_rx_t *frame = &rx[rx_write++];
  *frame = (host_rx_t){0};
  frame->header.Identifier = id;
  frame->header.IdType = extended ? FDCAN_EXTENDED_ID : FDCAN_STANDARD_ID;
  frame->header.RxFrameType = remote ? FDCAN_REMOTE_FRAME : FDCAN_DATA_FRAME;
  frame->header.FDFormat = fd ? FDCAN_FD_CAN : FDCAN_CLASSIC_CAN;
  frame->header.DataLength = (uint32_t)dlc;
  if (size)
    memcpy(frame->data, data, size);
  return true;
}
/**
 * Model one available transmit slot, without bitrate or arbitration simulation.
 *
 * Input: handle is deliberately ignored. Returns one available slot unconditionally;
 * actual pending-request rejection occurs in AddMessageToTxFifoQ. The fake does not
 * reproduce a hardware FIFO fill level.
 */
uint32_t HAL_FDCAN_GetTxFifoFreeLevel(FDCAN_HandleTypeDef *handle) {
  (void)handle;
  return 1U;
}
/**
 * Capture the actual request generated by production C.
 *
 * Inputs: header and data are valid production request buffers; handle is ignored. Returns
 * HAL_ERROR if the previous captured request was not consumed; otherwise copies
 * header/eight bytes, sets tx_pending and returns HAL_OK. This function does not transmit
 * externally.
 */
HAL_StatusTypeDef HAL_FDCAN_AddMessageToTxFifoQ(FDCAN_HandleTypeDef *handle,
                                                FDCAN_TxHeaderTypeDef *header,
                                                uint8_t *data) {
  (void)handle;
  if (tx_pending)
    return HAL_ERROR;
  outgoing.header = *header;
  memcpy(outgoing.data, data, 8);
  tx_pending = true;
  return HAL_OK;
}
/**
 * Consume a captured request once.
 *
 * Input: tx is writable request storage. Returns false without consuming when tx is null
 * or no request is pending. On true it copies outgoing then clears tx_pending, making the
 * one-slot sink available for the next request.
 */
bool dashboard_host_take_tx(dashboard_host_tx_t *tx) {
  if (!tx_pending || tx == NULL)
    return false;
  *tx = outgoing;
  tx_pending = false;
  return true;
}
/**
 * Expose the remaining receive batch.
 *
 * Inputs: handle/fifo are ignored. Returns queued-but-not-read entries as rx_write-
 * rx_read; no hardware filtering or overflow interrupt behavior is emulated.
 */
uint32_t HAL_FDCAN_GetRxFifoFillLevel(FDCAN_HandleTypeDef *handle, uint32_t fifo) {
  (void)handle;
  (void)fifo;
  return rx_write - rx_read;
}
/**
 * Copy the vendor DLC byte count into the production driver's receive buffer.
 *
 * Inputs: writable header/data buffers; handle/fifo ignored. Returns HAL_ERROR when empty,
 * otherwise copies the header and full DLC-sized bytes (up to 64), consumes a slot and
 * resets both indices only after the batch drains. The caller must provide 64-byte RX
 * capacity; malformed protocol frames still reach production validation.
 */
HAL_StatusTypeDef HAL_FDCAN_GetRxMessage(FDCAN_HandleTypeDef *handle,
                                         uint32_t fifo,
                                         FDCAN_RxHeaderTypeDef *header,
                                         uint8_t *data) {
  static const uint8_t lengths[16] = {0, 1, 2, 3, 4, 5, 6, 7, 8, 12, 16, 20, 24, 32, 48, 64};
  (void)handle;
  (void)fifo;
  if (rx_read == rx_write)
    return HAL_ERROR;
  *header = rx[rx_read].header;
  memcpy(data, rx[rx_read].data, lengths[header->DataLength]);
  if (++rx_read == rx_write)
    rx_read = rx_write = 0;
  return HAL_OK;
}
